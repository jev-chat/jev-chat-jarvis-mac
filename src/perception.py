def _is_noise(b: TextBlock) -> bool:
    if b.conf < MIN_CONF or len(b.text) < MIN_TEXT_LEN:
        return True
    if TIMESTAMP_RE.match(b.text):
        return True
    return any(re.search(pat, b.text) for pat in UI_NOISE)


def extract_chat_title(blocks: list[TextBlock], chat_left=CHAT_PANE_X_MIN) -> str:
    """Read the conversation name from the chat pane's header band.

    Two rows live up there: the title itself and (when a chat is collapsed) a
    "folded chats" banner. We take the topmost readable band and drop the banner.
    """
    cands = [b for b in blocks
             if b.x >= chat_left and b.y > TITLE_BAR_Y_MAX
             and not _is_noise(b)]
    # No length cap on purpose: an empty title collides reply keys across chats
    # (key = (chat_title, text)), which is worse than the occasional single-glyph
    # OCR smudge promoted to a title.
    # WeChat titles are left-aligned; centered headers would need layout detection.
    # A real contact name can be one character, so length cannot tell title from controls.
    starts = [b for b in cands if b.x < (chat_left + 1) / 2]
    if not starts:
        return ""
    top_y = max(b.y for b in starts)
    band = sorted((b for b in cands if abs(top_y - b.y) < 0.03), key=lambda b: b.x)
    keep = [band[0]]
    for b in band[1:]:
        # Join adjacent OCR fragments, including a short suffix; stop before controls.
        if b.x - keep[-1].x_right > 1.5 * max(b.h, keep[-1].h):
            break
        keep.append(b)
    title = " ".join(b.text for b in keep).strip()
    # WeChat appends a changing member count; it is not part of the conversation key.
    return re.sub(r"\s*[（(]\s*\d+\s*[）)]\s*$", "", title).strip()


def message_side(x: float, width: float, chat_left=CHAT_PANE_X_MIN) -> str:
    """Conservative text geometry: a center alone cannot identify a wide bubble.

    Only accept text anchored clearly to one side of the calibrated chat pane.
    Wide text spanning both anchors and isolated central fragments are ambiguous;
    keep them for context/overlay, but never treat them as an incoming reply target.
    """
    right = x + width
    pane = max(.01, 1.0 - chat_left)
    rel_x = (x - chat_left) / pane
    rel_right = (right - chat_left) / pane
    if rel_x >= .50 or (rel_x >= .18 and rel_right >= .72):
        return "me"
    if rel_x <= .30 and rel_right < .72:
        return "them"
    return "unknown"


def _is_public_info(text: str) -> bool:
    """Whether text is a WeChat-generated row shared with the whole conversation."""
    compact = re.sub(r"\s+", "", text).strip("。. ")
    return bool(compact and PUBLIC_INFO_RE.fullmatch(compact))


def _resolve_short_unknown_sides(messages: list[Message]) -> None:
    """Resolve only short unknown rows that align with both known chat anchors.

    Vision places a punctuation-only or punctuation-prefixed text box a few pixels to
    the right of an ordinary Chinese glyph. Near the conservative x=.50 boundary that
    can turn a clearly left-aligned incoming bubble into ``unknown``; the HUD then falls
    back to an older incoming message. Use the repeated left edge of known incoming text
    and repeated right edge of known outgoing text as evidence, but only when both sides
    are visible and the short row is decisively closer to one. Wide/central rows remain
    unknown, preserving the no-reply-on-ambiguous-message safety rule.
    """
    them_lefts = [m.x for m in messages if m.side == "them"]
    me_rights = [m.x + m.w for m in messages if m.side == "me"]
    if not them_lefts or not me_rights:
        return
    them_anchor = sorted(them_lefts)[len(them_lefts) // 2]
    me_anchor = sorted(me_rights)[len(me_rights) // 2]
    for m in messages:
        if m.side != "unknown" or m.w > .30:
            continue
        them_delta = abs(m.x - them_anchor)
        me_delta = abs(m.x + m.w - me_anchor)
        if them_delta <= .04 and them_delta + .04 < me_delta:
            m.side = "them"
        elif me_delta <= .04 and me_delta + .04 < them_delta:
            m.side = "me"


def extract_messages(blocks: list[TextBlock], max_messages: int = 12, input_top=None,
                     chat_left=CHAT_PANE_X_MIN,
                     defer_small_sender_filter: bool = False) -> list[Message]:
    """Turn raw OCR blocks into an ordered list of chat messages (bottom = newest)."""
    chat = [b for b in blocks
            if b.x >= chat_left
            and (INPUT_AREA_Y_MIN if input_top is None else 1.0 - input_top) < b.y < TITLE_BAR_Y_MAX
            and not _is_noise(b)]
    if not chat:
        return []

    # Vision y is bottom-origin and bb.origin.y is the box's BOTTOM edge. Convert to a
    # top-origin TOP edge (1 - y - h) so the stored y is literal: "distance from the
    # pane's top to where this box starts". The old 1 - y stored the bottom edge's
    # distance from the top — orderings and gap thresholds did not care (the transform
    # is monotonic), but the YOLO overlay draws y as the top edge and every box sank by
    # one box-height. Sorting and the fold/group logic below are unchanged either way.
    for b in chat:
        b.y = 1.0 - b.y - b.h
    chat.sort(key=lambda b: b.y)

    # group blocks that sit on the same visual line
    lines: list[list[TextBlock]] = []
    for b in chat:
        if lines and abs(b.y - lines[-1][0].y) < 0.012:
            lines[-1].append(b)
        else:
            lines.append([b])

    merged = []
    for group in lines:
        group.sort(key=lambda b: b.x)
        text = " ".join(b.text for b in group)
        merged.append(TextBlock(text=text, conf=min(b.conf for b in group),
                                x=min(b.x for b in group), y=group[0].y,
                                w=max(b.x_right for b in group) - min(b.x for b in group),
                                h=max(b.h for b in group)))

    def classify(block: TextBlock) -> str:
        return "public" if _is_public_info(block.text) else message_side(
            block.x, block.w, chat_left)

    per_line = sorted(merged, key=lambda b: b.y)
    # A long centered system notice may be returned as two or three OCR rows. Join it
    # before direction and sender-name inference; otherwise each fragment looks like a
    # normal left/right message even though their complete text is a public row.
    public_joined: list[TextBlock] = []
    i = 0
    while i < len(per_line):
        if _is_public_info(per_line[i].text):
            public_joined.append(per_line[i])
            i += 1
            continue
        joined = None
        for size in range(min(3, len(per_line) - i), 1, -1):
            chunk = per_line[i:i + size]
            # Do not swallow a complete public row into the ordinary message before it.
            if any(_is_public_info(part.text) for part in chunk[1:]):
                continue
            if any(not 0 <= chunk[j + 1].y - chunk[j].y < .06
                   for j in range(len(chunk) - 1)):
                continue
            text = "\n".join(part.text for part in chunk)
            if not _is_public_info(text):
                continue
            left = min(part.x for part in chunk)
            right = max(part.x_right for part in chunk)
            top = chunk[0].y
            bottom = max(part.y + part.h for part in chunk)
            joined = TextBlock(text=text, conf=min(part.conf for part in chunk),
                               x=left, y=top, w=right - left, h=bottom - top)
            i += size
            break
        if joined is None:
            joined = per_line[i]
            i += 1
        public_joined.append(joined)
    per_line = public_joined

    # fold continuation lines (same side, tight vertical gap, no new sender header)
    # Classify sender headers BEFORE folding; otherwise a tight nickname/body pair
    # becomes one multiline message and the old post-fold name detector misses it.
    # Compare adjacent font heights rather than a fraction of the window height.
    headers = set()
    for i, b in enumerate(per_line[:-1]):
        nxt = per_line[i + 1]
        if (i > 0 and QUOTE_LINE_RE.match(b.text) and b.h <= .026
                and per_line[i - 1].h >= .03
                and 0 <= b.y - per_line[i - 1].y <= .045
                and abs(b.x - per_line[i - 1].x) < .02):
            continue  # an inset quoted preview, not the next bubble's sender
        if (classify(b) == classify(nxt) == "them"
                and len(b.text) <= 32 and b.h <= nxt.h * .78
                and abs(b.x - nxt.x) < .03
                and b.h <= nxt.y - b.y <= max(.16, b.h * 4)):
            headers.add(i)
    messages: list[Message] = []
    pending_sender = None
    for i, b in enumerate(per_line):
        if i in headers:
            pending_sender = b.text.strip().rstrip("：:")
            continue
        side = classify(b)
        # fold against the LAST folded line, not the message's first: comparing against
        # the first line made every line from the third on measure ≥2 line-pitches away,
        # so any 3+ line message was split into ≤2-line chunks — the judge then only ever
        # saw the tail chunk, and the overlay drew a box per chunk
        gap = (b.y - messages[-1].last_y) if messages else 1.0
        # OCR gives us text boxes, not bubble boxes.  In a right-aligned outgoing bubble,
        # wrapped text is left-aligned inside the bubble: its long first row reaches the
        # right anchor and classifies as ``me``, while a short second row can look like
        # ``them`` when judged in isolation.  A tight, left-aligned next row is therefore
        # continuation evidence independent of its provisional side.  Once folded, the
        # union bounds reach the correct anchor and we classify the whole bubble below.
        x_shift = abs(b.x - messages[-1].x) if messages else 1.0
        aligned = messages and x_shift < 0.02
        compatible = messages and side != "public" and messages[-1].side != "public" \
            and (side == messages[-1].side
                                   or "unknown" in (side, messages[-1].side))
        # When both provisional sides are known but opposite, demand much stronger
        # same-bubble evidence.  This catches a short wrapped outgoing row whose left
        # edge is effectively identical to the long row above, without joining two
        # genuinely opposite bubbles that merely happen to start near each other.
        wrapped_opposite = (messages and side != messages[-1].side
                            and side not in ("unknown", "public")
                            and messages[-1].side not in ("unknown", "public")
                            and x_shift < 0.008 and 0 <= gap < 0.038)
        if (pending_sender is None and aligned and 0 <= gap < 0.045
                and (compatible or wrapped_opposite)):
            m = messages[-1]
            quoted = QUOTE_LINE_RE.match(b.text)
            # Quoted previews use smaller, muted type inside the same bubble. A plain
            # "name: words" line at normal body size stays ordinary message text.
            quote_line = (m.side in ("them", "me") and b.h <= .026
                          and m.h >= .03 and quoted is not None
                          and "://" not in b.text)
            if quote_line:
                m.quote_sender = quoted.group(1).strip()
                m.quote_text = quoted.group(2).strip()
            elif m.quote_text and b.h <= .026:
                m.quote_text += "\n" + b.text
            else:
                m.lines.append(b.text)
                m.text = "\n".join(m.lines)
            m.conf = min(m.conf, b.conf)
            # grow the bounding box to cover the folded line (m.y stays the top line's)
            bottom = max(m.y + m.h, b.y + b.h)
            right = max(m.x + m.w, b.x_right)
            m.x = min(m.x, b.x)
            m.w = right - m.x
            if not quote_line and not (m.quote_text and b.h <= .026):
                m.side = "public" if _is_public_info(m.text) else message_side(
                    m.x, m.w, chat_left)
            m.h = bottom - m.y
            m.last_y = b.y
        else:
            messages.append(Message(text=b.text, side=side, y=b.y, conf=b.conf,
                                    h=b.h, lines=[b.text], x=b.x, w=b.w,
                                    last_y=b.y, sender=pending_sender))
            pending_sender = None

    _resolve_short_unknown_sides(messages)
    # Stray sender names: WeChat renders one above every bubble — including
    # image-only messages, whose media OCR cannot read — so a short them line that
    # ended up as a message of its own is a name, never something to judge. Our own
    # bubbles have no name above them, and short outgoing text can be just as small
    # in a tall window, so only the them side is dropped. (#62)
    small_incoming = [
        m for m in messages
        if (m.side == "them" and "\n" not in m.text
            and len(m.text) <= 16 and m.h < USERNAME_H_MAX)
    ]
    # Two aligned small incoming rows are much more likely to be successive short
    # bubbles ("不够啊" / "还要交社保") than two orphaned sender labels.
    # Preserve that sequence while still dropping an isolated name above image/voice
    # content, including when an outgoing message happens to follow it.
    short_bubble_ids = {
        id(m) for m in small_incoming
        if any(other is not m
               and abs(other.y - m.y) <= .12
               and abs(other.x - m.x) <= .04
               for other in small_incoming)
    }
    small_incoming_ids = {id(m) for m in small_incoming}
    for m in small_incoming:
        if id(m) not in short_bubble_ids:
            m.suspected_sender = True
    if defer_small_sender_filter:
        return messages[-max_messages:]
    named = [m for m in messages
             if id(m) not in small_incoming_ids or id(m) in short_bubble_ids]
    return named[-max_messages:]


def looks_like_sender_name(msg: Message, following: Message | None) -> bool:
    """Heuristic: group chats render the sender name as a short line above the bubble."""
    if following is None:
        return False
    t = msg.text.strip()
    if len(t) > 16 or "\n" in t:
        return False
    gap = following.y - msg.y
    return gap > 0.045


