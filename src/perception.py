@dataclass
class TextBlock:
    text: str
    conf: float
    x: float
    y: float
    w: float
    h: float

    @property
    def x_right(self) -> float:
        return self.x + self.w

    @property
    def x_center(self) -> float:
        return self.x + self.w / 2


@dataclass
class Message:
    text: str
    side: str          # "them" | "me" | "public" | "unknown"
    y: float           # normalized, top-origin for readability
    conf: float
    h: float = 0.0
    sender: str | None = None
    lines: list[str] = field(default_factory=list)
    # normalized bounding box, kept spanning every folded line — the YOLO overlay draws
    # one box per message, so a 3-line message must cover all 3 lines, not its first
    x: float = 0.0
    w: float = 0.0
    last_y: float = 0.0     # top of the most recent folded line; fold bookkeeping only
    visual_only: bool = False  # a bubble exists, but Vision returned no readable text
    suspected_sender: bool = False  # small isolated OCR row; pixels decide in production
    quote_sender: str | None = None
    quote_text: str | None = None
    analysis_text: str | None = None  # consecutive messages sent to the models
    analysis_body: str | None = None  # exclude quoted history from intent judgment
    analysis_parts: tuple[int, ...] = ()


QUOTE_LINE_RE = re.compile(r"^\s*[|｜]?\s*([^:：\n]{1,24})[:：]\s*(\S.*)$")


def reply_span(messages: list[Message], newest: Message, limit: int = 3) -> list[Message]:
    """Adjacent, visibly separate bubbles from one sender form one reply target."""
    try:
        index = next(i for i, m in enumerate(messages) if m is newest)
    except StopIteration:
        return [newest]
    span = [newest]
    while index > 0 and len(span) < limit:
        previous = messages[index - 1]
        current = span[0]
        gap = current.y - (previous.y + previous.h)
        if (previous.side != "them" or previous.visual_only
                or previous.sender != current.sender or not 0 <= gap <= .07):
            break
        span.insert(0, previous)
        index -= 1
    return span


def reply_text(messages: list[Message]) -> str:
    """Keep a quoted preview attributed, separate from each bubble's own words."""
    parts = []
    for message in messages:
        parts.append(message.text)
        quoted = getattr(message, "quote_text", None)
        if quoted:
            who = getattr(message, "quote_sender", None) or "对方"
            parts.append(f"[引用 {who}: {quoted}]")
    return "\n".join(parts)


