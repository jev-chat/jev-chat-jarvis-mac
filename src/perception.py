# Fixed grid, independent of window size: a resize re-fingerprints as "different" instead
# of aliasing onto a match. At 128x224 a single chat character still covers a handful of
# cells, so the smallest change anyone could send shifts far more bytes than noise.
_FP_W, _FP_H = 128, 224


def _fingerprint(image, input_top=None, chat_left=CHAT_PANE_X_MIN) -> bytes | None:
    """The chat pane (title band down to just above the input box) as a small grayscale
    thumbnail; None when anything in the pipeline refuses.

    read_conversation() compares this between ticks: the same picture means the pixels
    did not move, so OCR cannot have anything new to report and its ~300 ms can be
    skipped. The input box is excluded on purpose — the caret blinks there, and it would
    keep a quiet screen looking busy forever. The chat list is excluded for the same
    reason (unread badges), which is also why the crop starts at CHAT_PANE_X_MIN.
    """
    import ctypes

    try:
        w = Quartz.CGImageGetWidth(image)
        h = Quartz.CGImageGetHeight(image)
        # Layout constants here are bottom-origin (Vision's convention); CGImage cropping
        # is top-origin, so the band "input-area top edge .. window top" becomes
        # y=0 .. (1 - INPUT_AREA_Y_MIN) from the top.
        crop = Quartz.CGImageCreateWithImageInRect(
            image,
            Quartz.CGRectMake(int(chat_left * w), 0,
                              int((1.0 - chat_left) * w),
                              int((1.0 - INPUT_AREA_Y_MIN if input_top is None else input_top) * h)))
        cs = Quartz.CGColorSpaceCreateDeviceGray()
        buf = ctypes.create_string_buffer(_FP_W * _FP_H)
        ctx = Quartz.CGBitmapContextCreate(
            buf, _FP_W, _FP_H, 8, _FP_W, cs, Quartz.kCGImageAlphaNone)
        Quartz.CGContextDrawImage(ctx, Quartz.CGRectMake(0, 0, _FP_W, _FP_H), crop)
        return buf.raw
    except Exception:
        return None


def _same_frame(a: bytes | None, b: bytes | None) -> bool:
    """True when two fingerprints are the same picture.

    Exact equality covers the static case at C speed. When it fails, a tolerant count
    decides: a few small byte deltas is rendering noise (treat as same, skip OCR),
    anything a person sent rewrites whole glyph cells (treat as changed). Missing a real
    change would mean missing a message, so the threshold sits well under what one
    character produces.
    """
    if a is None or b is None:
        return False
    if a == b:
        return True
    return sum(1 for x, y in zip(a, b) if abs(x - y) >= 8) < 6


def _incoming_bubble_boxes(image, chat_left: float, input_top: float) -> list[tuple]:
    """Find light/dark neutral incoming bubbles that contain no OCR text.

    Vision intentionally suppresses punctuation-only rows such as ``...``.  We do not
    attempt to invent their text; this tiny colour/shape pass only proves that a rounded
    incoming bubble exists below the last readable message, allowing the HUD to stop
    instead of replying to an older sentence.  Coordinates are normalized, top-origin.

    The dominant chat background is measured from every frame, so light/dark themes and
    a resized sidebar are both handled without fixed RGB values.  Only broad, near-neutral
    filled runs qualify; avatars, glyph strokes and green outgoing bubbles do not.
    """
    import ctypes

    try:
        source_w = Quartz.CGImageGetWidth(image)
        source_h = Quartz.CGImageGetHeight(image)
        w = 320
        h = max(120, round(source_h * w / source_w))
        buf = ctypes.create_string_buffer(w * h * 4)
        ctx = Quartz.CGBitmapContextCreate(
            buf, w, h, 8, w * 4, Quartz.CGColorSpaceCreateDeviceRGB(),
            Quartz.kCGImageAlphaPremultipliedLast)
        if ctx is None:
            return []
        Quartz.CGContextDrawImage(ctx, Quartz.CGRectMake(0, 0, w, h), image)
        data = buf.raw
    except Exception:
        return []

    left = max(1, min(w - 2, round(chat_left * w)))
    top = max(1, round((1.0 - TITLE_BAR_Y_MAX) * h))
    bottom = min(h - 2, round(input_top * h))
    if bottom - top < 20:
        return []

    def rgb(x, y):
        i = (y * w + x) * 4
        return data[i], data[i + 1], data[i + 2]

    samples = [rgb(x, y) for y in range(top, bottom, 12)
               for x in range(left + 4, w - 4, 12)]
    if not samples:
        return []
    # The conversation background owns most pixels; channel medians are stable even
    # when several large bubbles are on screen.
    bg = tuple(sorted(c[i] for c in samples)[len(samples) // 2] for i in range(3))
    bg_luma = sum(bg) / 3

    def bubble_pixel(x, y):
        c = rgb(x, y)
        spread = max(c) - min(c)
        luma = sum(c) / 3
        delta = abs(luma - bg_luma)
        return spread <= 10 and 6 <= delta <= 75

    # One run per row is enough for incoming bubbles: they live in the left half of the
    # chat pane. Allow tiny holes so black punctuation inside the fill does not split it.
    pane_w = w - left
    row_runs = []
    scan_right = round(left + pane_w * .72)
    for y in range(top, bottom):
        start = None
        last = None
        gap = 0
        for x in range(left, scan_right):
            if bubble_pixel(x, y):
                if start is None:
                    start = x
                last = x
                gap = 0
            elif start is not None:
                gap += 1
                if gap > 3:
                    if last - start >= max(10, round(w * .035)):
                        row_runs.append((y, start, last))
                    start = last = None
                    gap = 0
        if start is not None and last - start >= max(10, round(w * .035)):
            row_runs.append((y, start, last))

    components = []
    for y, x0, x1 in row_runs:
        match = None
        for comp in reversed(components[-12:]):
            if y - comp[4] > 2:
                continue
            overlap = min(x1, comp[2]) - max(x0, comp[1])
            if overlap >= min(x1 - x0, comp[2] - comp[1]) * .45:
                match = comp
                break
        if match is None:
            components.append([y, x0, x1, y, y])  # top, left, right, first, last
        else:
            match[0] = min(match[0], y)
            match[1] = min(match[1], x0)
            match[2] = max(match[2], x1)
            match[4] = y

    boxes = []
    for y0, x0, x1, _first, y1 in components:
        bw, bh = x1 - x0 + 1, y1 - y0 + 1
        if bw < w * .04 or bh < h * .012 or bh > h * .18:
            continue
        rel_left = (x0 - left) / pane_w
        rel_right = (x1 - left) / pane_w
        if rel_left > .35 or rel_right > .72:
            continue
        boxes.append((x0 / w, y0 / h, bw / w, bh / h))
    return boxes


def _append_unreadable_incoming(image, messages: list[Message], chat_left: float,
                                input_top: float) -> None:
    """Reconcile incoming bubbles, then append a placeholder for one Vision omitted.

    Text geometry is only a first pass.  A quoted row inside a wide incoming bubble can
    sit far enough right to look outgoing, and an unusually tight group nickname can be
    folded into the body.  The neutral bubble pixels settle both cases here, where the
    screenshot is still available.
    """
    boxes = _incoming_bubble_boxes(image, chat_left, input_top)

    def message_matches(box, message):
        x, y, w, h = box
        return (x - .02 <= message.x <= x + w + .02
                and y - .012 <= message.y + message.h / 2 <= y + h + .012)

    def sender_above(box, message):
        """Strong visual evidence that a text row is a group nickname for ``box``."""
        x, y, w, _h = box
        gap = y - (message.y + message.h)
        text = message.text.strip()
        return (message.side in ("them", "unknown")
                and message.sender is None and not message.visual_only
                and message.side != "public" and "\n" not in text
                and 0 < len(text) <= 32
                and -0.008 <= gap <= 0.035
                and x - .04 <= message.x <= x + min(w, .16)
                and message.x + message.w <= x + w + .04
                and not message_matches(box, message))

    # Font size is only a hint in group chats: display-name badges, unusual glyphs and
    # window scaling often make a nickname as tall as the body, which is why James/Lee
    # in real screenshots escaped the pre-OCR-row heuristic. The actual incoming bubble
    # is stronger evidence. A row immediately above and outside that bubble is the
    # sender; bind it to the first message inside the bubble and remove the fake message.
    sender_for_box: dict[tuple, Message] = {}
    claimed_sender_ids = set()
    for box in boxes:
        bodies = [m for m in messages if m.side != "public" and message_matches(box, m)]
        candidates = [m for m in messages if sender_above(box, m)]
        if not candidates:
            continue
        sender_row = min(candidates, key=lambda m: abs(box[1] - (m.y + m.h)))
        sender_for_box[box] = sender_row
        claimed_sender_ids.add(id(sender_row))
        if bodies:
            body = min(bodies, key=lambda m: m.y)
            if body.sender is None:
                body.sender = sender_row.text.strip().rstrip("：:")

    if claimed_sender_ids:
        messages[:] = [m for m in messages if id(m) not in claimed_sender_ids]

    # A tiny isolated OCR row can be either a group-chat sender label or a real short
    # bubble such as "买了". Text geometry alone cannot distinguish them. Production
    # extraction therefore defers the decision until these pixel-derived bubble boxes
    # are available: text inside a neutral incoming bubble stays; text floating above an
    # image/voice item is the sender name and is removed.
    suspected = [m for m in messages if m.suspected_sender]
    confirmed_ids = {
        id(m) for m in suspected if any(message_matches(box, m) for box in boxes)
    }
    if suspected:
        messages[:] = [m for m in messages
                       if not m.suspected_sender or id(m) in confirmed_ids]
    if not boxes:
        return

    # Anything physically inside a neutral incoming bubble belongs to the other side,
    # even when a quoted preview is right-shifted enough for geometry to call it mine.
    # Public rows have no bubble and remain semantic system information even if a noisy
    # colour component happens to overlap them.
    for m in messages:
        matching = [box for box in boxes if message_matches(box, m)]
        if not matching or m.side == "public":
            continue
        m.side = "them"
        box = min(matching, key=lambda b: b[2] * b[3])
        _bx, bubble_y, _bw, _bh = box
        # If extraction folded a tight nickname into the first body line, the first
        # line starts above the bubble while a later line lands inside it. Restore that
        # line as attribution. Ordinary wrapped body text starts below the bubble top,
        # so it cannot enter this branch.
        embedded_lines = [part.strip() for part in m.text.splitlines() if part.strip()]
        candidate_lines = m.lines if len(m.lines) > 1 else embedded_lines
        body_reaches_bubble = (m.last_y >= bubble_y - .012
                               or m.y + m.h > bubble_y + .001)
        if (m.sender is None and len(candidate_lines) > 1
                and m.y < bubble_y - .006 and body_reaches_bubble
                and len(candidate_lines[0].strip()) <= 32):
            sender = candidate_lines[0].strip().rstrip("：:")
            if sender:
                old_bottom = m.y + m.h
                m.sender = sender
                m.lines = candidate_lines[1:]
                m.text = "\n".join(m.lines)
                m.y = bubble_y
                m.h = max(.001, old_bottom - m.y)

    def matched(box):
        return any(message_matches(box, m) for m in messages)

    latest_bottom = max((m.y + m.h for m in messages), default=.10)
    candidates = [b for b in boxes if not matched(b) and b[1] > latest_bottom + .008]
    if not candidates:
        return
    x, y, w, h = max(candidates, key=lambda b: b[1])
    punctuation = _punctuation_only_text(image, (x, y, w, h))
    recovered = None if punctuation else _short_bubble_text(image, (x, y, w, h))
    text = punctuation or (recovered[0] if recovered else "[未识别文字/表情]")
    confidence = 0.70 if punctuation else recovered[1] if recovered else 0.0
    sender_row = sender_for_box.get((x, y, w, h))
    messages.append(Message(
        text=text, side="them", y=y, conf=confidence,
        h=h, lines=[text], x=x, w=w, last_y=y,
        sender=(sender_row.text.strip().rstrip("：:") if sender_row else None),
        visual_only=not bool(punctuation or recovered)))


def _punctuation_only_text(image, box: tuple) -> str | None:
    """Recognize 2–6 tiny repeated full stops inside a Vision-omitted bubble.

    Vision commonly returns no observation at all for ``。。。``.  The bubble pass
    already gives us a very small, safe crop.  Inside that crop, a run of full stops is a
    distinctive set of equally small dark components on one horizontal baseline.  This
    deliberately recognizes only that narrow shape; emoji, stickers and arbitrary marks
    remain the honest ``[未识别文字/表情]`` placeholder.
    """
    import ctypes

    try:
        source_w = Quartz.CGImageGetWidth(image)
        source_h = Quartz.CGImageGetHeight(image)
        bx, by, bw, bh = box
        x0 = max(0, round(bx * source_w))
        y0 = max(0, round(by * source_h))
        w = min(source_w - x0, max(1, round(bw * source_w)))
        h = min(source_h - y0, max(1, round(bh * source_h)))
        crop = Quartz.CGImageCreateWithImageInRect(
            image, Quartz.CGRectMake(x0, y0, w, h))
        buf = ctypes.create_string_buffer(w * h * 4)
        ctx = Quartz.CGBitmapContextCreate(
            buf, w, h, 8, w * 4, Quartz.CGColorSpaceCreateDeviceRGB(),
            Quartz.kCGImageAlphaPremultipliedLast)
        if crop is None or ctx is None:
            return None
        Quartz.CGContextDrawImage(ctx, Quartz.CGRectMake(0, 0, w, h), crop)
        data = buf.raw
    except Exception:
        return None

    # Ignore rounded edges and anti-aliasing at the bubble boundary.
    mx = max(2, round(w * .07))
    my = max(2, round(h * .10))

    def rgb(x, y):
        i = (y * w + x) * 4
        return data[i], data[i + 1], data[i + 2]

    samples = [rgb(x, y) for y in range(my, max(my + 1, h - my), 2)
               for x in range(mx, max(mx + 1, w - mx), 2)]
    if not samples:
        return None
    bubble_luma = sorted(sum(c) / 3 for c in samples)[len(samples) // 2]
    dark_limit = min(170, bubble_luma - 45)
    ink = set()
    for y in range(my, h - my):
        for x in range(mx, w - mx):
            c = rgb(x, y)
            if sum(c) / 3 <= dark_limit and max(c) - min(c) <= 55:
                ink.add((x, y))
    if not ink:
        return None

    total_ink = len(ink)
    components = []
    while ink:
        stack = [ink.pop()]
        points = []
        while stack:
            px, py = stack.pop()
            points.append((px, py))
            for nx in (px - 1, px, px + 1):
                for ny in (py - 1, py, py + 1):
                    if (nx, ny) in ink:
                        ink.remove((nx, ny))
                        stack.append((nx, ny))
        x_min = min(p[0] for p in points)
        x_max = max(p[0] for p in points)
        y_min = min(p[1] for p in points)
        y_max = max(p[1] for p in points)
        cw, ch = x_max - x_min + 1, y_max - y_min + 1
        if 2 <= len(points) <= 40 and cw <= 8 and ch <= 8:
            components.append((len(points), x_min, y_min, x_max, y_max))

    if not 2 <= len(components) <= 6:
        return None
    # Random emoji fragments may contain several dots, but not several same-sized dots
    # on one baseline with almost all dark ink accounted for.
    if sum(c[0] for c in components) < total_ink * .72:
        return None
    centers = sorted(((c[1] + c[3]) / 2, (c[2] + c[4]) / 2,
                      c[3] - c[1] + 1, c[4] - c[2] + 1)
                     for c in components)
    if max(c[1] for c in centers) - min(c[1] for c in centers) > max(3, h * .12):
        return None
    if max(c[2] for c in centers) - min(c[2] for c in centers) > 3:
        return None
    if max(c[3] for c in centers) - min(c[3] for c in centers) > 3:
        return None
    gaps = [centers[i + 1][0] - centers[i][0] for i in range(len(centers) - 1)]
    if any(g < 3 or g > max(20, h * .8) for g in gaps):
        return None
    return "。" * len(components)


def _short_bubble_text(image, box: tuple) -> tuple[str, float] | None:
    """Retry OCR on one visually confirmed bubble at a much larger effective size.

    The full chat pane intentionally runs at nominal 1x for speed. That is enough for
    ordinary lines, but Vision occasionally omits a one-character reply such as ``可``
    altogether. Cropping the already detected bubble makes the same glyph occupy most
    of Vision's input; scaling the crop avoids the framework's small-image floor. This
    path only runs for an otherwise unmatched bubble, so normal reads pay nothing.
    """
    try:
        source_w = Quartz.CGImageGetWidth(image)
        source_h = Quartz.CGImageGetHeight(image)
        bx, by, bw, bh = box
        raw_w = max(1, round(bw * source_w))
        raw_h = max(1, round(bh * source_h))
        # The colour pass sees uninterrupted bubble fill, not its exact outer bounds:
        # glyphs and the debug overlay can split/shorten the component. Expand relative
        # to that component so the full single glyph survives the crop.
        pad_x = max(2, round(raw_w * .18))
        pad_top = max(2, round(raw_h * .18))
        pad_bottom = max(4, round(raw_h * .65))
        x0 = max(0, round(bx * source_w) - pad_x)
        y0 = max(0, round(by * source_h) - pad_top)
        width = min(source_w - x0, raw_w + 2 * pad_x)
        height = min(source_h - y0, raw_h + pad_top + pad_bottom)
        crop = Quartz.CGImageCreateWithImageInRect(
            image, Quartz.CGRectMake(x0, y0, width, height))
        if crop is None:
            return None

        scale = min(8.0, max(3.0, 128.0 / height))
        target_w = max(64, round(width * scale))
        target_h = max(64, round(height * scale))
        ctx = Quartz.CGBitmapContextCreate(
            None, target_w, target_h, 8, target_w * 4,
            Quartz.CGColorSpaceCreateDeviceRGB(),
            Quartz.kCGImageAlphaPremultipliedLast)
        if ctx is None:
            return None
        Quartz.CGContextSetRGBFillColor(ctx, 1, 1, 1, 1)
        Quartz.CGContextFillRect(ctx, Quartz.CGRectMake(0, 0, target_w, target_h))
        Quartz.CGContextSetInterpolationQuality(ctx, Quartz.kCGInterpolationHigh)
        Quartz.CGContextDrawImage(
            ctx, Quartz.CGRectMake(0, 0, target_w, target_h), crop)
        enlarged = Quartz.CGBitmapContextCreateImage(ctx)
        import Vision
        handler = Vision.VNImageRequestHandler.alloc().initWithCGImage_options_(
            enlarged, None)
        # Language correction is valuable for sentences but can suppress a valid
        # isolated character because it has no surrounding language context.
        blocks = _vision_blocks(
            handler, ("zh-Hans",), chat_only=False,
            language_correction=False, minimum_text_height=.005)
    except Exception:
        return None

    bubble_left = (round(bx * source_w) - x0) / width
    bubble_top = (round(by * source_h) - y0) / height
    bubble_right = (round(bx * source_w) + raw_w - x0) / width
    bubble_bottom = (round(by * source_h) + raw_h - y0) / height

    def inside_original_bubble(block):
        center_x = block.x + block.w / 2
        center_top = 1.0 - block.y - block.h / 2
        return (bubble_left - .06 <= center_x <= bubble_right + .06
                and bubble_top - .04 <= center_top <= bubble_bottom + .08)

    # This crop is already proven to be a bubble, so global UI words such as “发送”
    # and “搜索” are valid chat content here. Keep a stricter confidence threshold
    # instead of reusing _is_noise(), which would delete those legitimate short replies.
    readable = [b for b in blocks
                if b.conf >= SHORT_RETRY_MIN_CONF and b.text.strip()
                and inside_original_bubble(b)]
    if not readable:
        return None
    readable.sort(key=lambda b: (-b.y, b.x))
    text = "\n".join(b.text.strip() for b in readable if b.text.strip()).strip()
    if not text or len(text) > 120:
        return None
    return text, min(b.conf for b in readable)


